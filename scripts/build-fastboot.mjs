const corePath = 'live/core/game/game-core.js';
const basePath = 'live/core/loader/game-loader-base.js';
const bundlePath = 'live/core/loader/live-patches.bundle.js';
const runtimePath = 'live/core/game/game-runtime.js';
const buildInfoPath = 'live/core/config/build-info.js';

const [coreSource, baseSource, ...patchSources] = await Promise.all([
  readFile(fromRoot(corePath), 'utf8'),
  readFile(fromRoot(basePath), 'utf8'),
  ...patchFiles.map(file => readFile(fromRoot(file), 'utf8'))
]);

const buildId = createHash('sha256')
  .update(coreSource)
  .update(baseSource)
  .update(patchSources.join('\n'))
  .digest('hex')
  .slice(0, 16);

const utilitySource = String.raw`
window.__CRITTER_ARENA_PATCHES__ = [];
function one(source,name,pattern,replacement,required=true){
  const flags=pattern.flags.includes('g')?pattern.flags:pattern.flags+'g';
  const matches=[...source.matchAll(new RegExp(pattern.source,flags))];
  if(name==='hide arena beacon'&&!matches.length){console.warn('Optional LIVE patch missing: hide arena beacon; VS beacon is already moved off-map');return source;}
  if(name==='v7 export trust label'&&!matches.length){
    const fallback=/account\.securityTrust\s*=\s*'encrypted-v6';(?=\s*account\.securityRevision)/;
    if(fallback.test(source))return source.replace(fallback,"account.securityTrust = 'encrypted-v7';");
    console.warn('Optional LIVE patch missing: v7 export trust label; secure export remains compatible');
    return source;
  }
  if((name==='protect remaining players after fair play removal'||name==='handle recovery protection and disqualify removed cheater')&&!matches.length){console.warn('Optional LIVE patch missing: '+name+'; Fair Play compatibility was already normalized');return source;}
  if(name==='dynamic match badge'&&matches.length)return source.replace(new RegExp(pattern.source,flags),(...args)=>typeof replacement==='function'?replacement(...args):replacement);
  if(matches.length!==1){if(required)throw new Error('LIVE patch '+(matches.length?'ambiguous':'missing')+': '+name);console.warn('Optional LIVE patch '+(matches.length?'ambiguous':'missing')+': '+name);return source;}
  return source.replace(pattern,(...args)=>typeof replacement==='function'?replacement(...args):replacement);
}
function all(source,name,pattern,replacement,required=true){
  const flags=pattern.flags.includes('g')?pattern.flags:pattern.flags+'g';
  const regex=new RegExp(pattern.source,flags),matches=[...source.matchAll(regex)];
  if(!matches.length){if(required)throw new Error('LIVE patch missing: '+name);console.warn('Optional LIVE patch missing: '+name);return source;}
  return source.replace(regex,()=>replacement);
}
window.__CRITTER_PATCH_UTILS__={one,all};
`;

const patchBody = patchSources.map((source, index) => `\n/* ${patchFiles[index]} */\n${source.trim()}\n`).join('\n');
const bundleSource = `/* Generated by scripts/build-fastboot.mjs. Do not edit directly. */\n${patchBody}\nwindow.__CRITTER_PATCH_BUNDLE_MODE__='generated-single-file';\nwindow.__CRITTER_PATCH_BUNDLE_READY__=Promise.resolve(true);\n`;
await writeFile(fromRoot(bundlePath), bundleSource, 'utf8');

function createNoopNode() {
  return new Proxy(function noop() {}, {
    get(target, key) {
      if (key === 'style' || key === 'dataset' || key === 'classList') return createNoopNode();
      if (key === 'appendChild' || key === 'remove' || key === 'addEventListener' || key === 'setAttribute' || key === 'querySelector' || key === 'querySelectorAll') return createNoopNode();
      if (key === Symbol.iterator) return function* empty() {};
      return target[key] ?? createNoopNode();
    },
    apply() { return createNoopNode(); },
    set(target, key, value) { target[key] = value; return true; }
  });
}

let finalRuntime = '';
let latestBlob = null;
class BuildBlob {
  constructor(parts = []) {
    this.source = parts.map(part => String(part)).join('');
    latestBlob = this;
  }
}
class BuildURL extends URL {}
BuildURL.createObjectURL = () => 'blob:critter-fastboot-build';
BuildURL.revokeObjectURL = () => {};

const document = {
  head: {
    appendChild(node) {
      if (node?.src === 'blob:critter-fastboot-build' && latestBlob) {
        finalRuntime = latestBlob.source;
        queueMicrotask(() => node.onload?.());
      }
      return node;
    }
  },
  body: createNoopNode(),
  documentElement: createNoopNode(),
  createElement(tag) {
    if (String(tag).toLowerCase() === 'script') return { src: '', textContent: '', onload: null, onerror: null, remove() {}, addEventListener() {}, setAttribute() {}, dataset: {} };
    return createNoopNode();
  },
  getElementById() { return null; },
  querySelector() { return null; },
  querySelectorAll() { return []; },
  addEventListener() {},
  readyState: 'complete'
};

const sandbox = {
  console,
  document,
  location: { href: 'https://example.invalid/live/', protocol: 'https:', origin: 'https://example.invalid', pathname: '/live/' },
  navigator: { userAgent: 'FastBoot Builder', onLine: true },
  performance,
  URL: BuildURL,
  Blob: BuildBlob,
  Response,
  Request,
  Headers,
  TextEncoder,
  TextDecoder,
  AbortController,
  setTimeout,
  clearTimeout,
  setInterval,
  clearInterval,
  queueMicrotask,
  crypto: globalThis.crypto,
  fetch: async () => ({ ok: true, status: 200, statusText: 'OK', headers: new Headers(), text: async () => livePatchedCore })
};
sandbox.window = sandbox;
sandbox.globalThis = sandbox;
sandbox.self = sandbox;
sandbox.addEventListener = () => {};
sandbox.removeEventListener = () => {};
sandbox.__critterBootReport = () => {};
vm.createContext(sandbox);

vm.runInContext(utilitySource, sandbox, { filename: 'fastboot-patch-utils.js' });
for (let index = 0; index < patchSources.length; index += 1) {
  vm.runInContext(patchSources[index], sandbox, { filename: patchFiles[index] });
}

let livePatchedCore = coreSource;
for (const patch of sandbox.__CRITTER_ARENA_PATCHES__) livePatchedCore = patch(livePatchedCore);

vm.runInContext(baseSource, sandbox, { filename: basePath });
for (let attempt = 0; attempt < 100 && !finalRuntime; attempt += 1) {
  await new Promise(resolve => setTimeout(resolve, 10));
}
if (!finalRuntime) throw new Error('game-loader-base.js did not produce a runtime Blob.');

const runtimeSource = `/* Generated Fast Boot runtime ${buildId}. Do not edit directly. */\n(() => {\n'use strict';\n${utilitySource}\n${patchBody}\nwindow.__CRITTER_ARENA_UI__?.();\nwindow.__CRITTER_PREBUILT_RUNTIME__=true;\n${finalRuntime}\n})();\n`;
await writeFile(fromRoot(runtimePath), runtimeSource, 'utf8');

const buildInfoSource = await readFile(fromRoot(buildInfoPath), 'utf8');
const existingId = buildInfoSource.match(/buildId:\s*'([^']*)'/)?.[1] || '';
const existingGeneratedAt = buildInfoSource.match(/generatedAt:\s*'([^']*)'/)?.[1] || '';
const generatedAt = existingId === buildId && existingGeneratedAt ? existingGeneratedAt : new Date().toISOString();
const updatedBuildInfo = buildInfoSource.replace(
  /window\.CritterBuildInfo\s*=\s*Object\.freeze\(\{[^\n]*\}\);/,
  `window.CritterBuildInfo = Object.freeze({ buildId: '${buildId}', channel: 'github-pages', generatedAt: '${generatedAt}' });`
);
if (updatedBuildInfo === buildInfoSource && existingId !== buildId) throw new Error('Could not update CritterBuildInfo.');
await writeFile(fromRoot(buildInfoPath), updatedBuildInfo, 'utf8');

console.log(`Built Fast Boot ${buildId}: ${patchFiles.length} patches -> ${bundlePath} and ${runtimePath}`);
